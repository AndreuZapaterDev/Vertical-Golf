const GROUND_ROWS = 3;

/** Convierte el mapa de texto en la rejilla completa + lista de objetos */
export function parseLevel(index) {
  const meta = LEVELS[index];
  const lines = meta.map.replace(/^\n/, '').split('\n').map((l) => l.replace(/\r$/, ''));
  const grid = [];
  const objects = { gems: [], saws: [], bumpers: [], mushrooms: [], movers: [], crumbles: [] };
  let start = null;
  let hole = null;

  lines.forEach((raw, r) => {
    if (raw.length !== COLS - 2) console.warn(`[nivel ${index + 1}] fila ${r} tiene ${raw.length} columnas (deberían ser ${COLS - 2})`);
    const row = ('#' + raw.padEnd(COLS - 2, '.').slice(0, COLS - 2) + '#').split('');
    for (let c = 0; c < COLS; c++) {
      const ch = row[c];
      const cell = { c, r };
      if (ch === 'S') start = cell;
      else if (ch === 'H') hole = cell;
      else if (ch === '*') objects.gems.push(cell);
      else if (ch === 'X') objects.saws.push({ ...cell, range: 0 });
      else if (ch === 'Y') objects.saws.push({ ...cell, range: 30 });
      else if (ch === 'O') objects.bumpers.push(cell);
      else if (ch === 'M') objects.mushrooms.push(cell);
      if ('SH*XYOM'.includes(ch)) row[c] = '.';
    }
    // tramos de plataformas móviles y bloques frágiles
    for (const [ch, list] of [['P', objects.movers], ['C', objects.crumbles]]) {
      for (let c = 0; c < COLS; c++) {
        if (row[c] !== ch) continue;
        let n = 0;
        while (row[c + n] === ch) n++;
        list.push({ c, r, n });
        for (let k = 0; k < n; k++) row[c + k] = '.';
        c += n - 1;
      }
    }
    grid.push(row);
  });
  for (let i = 0; i < GROUND_ROWS; i++) grid.push('#'.repeat(COLS).split(''));

  return { ...meta, index, grid, rows: grid.length, groundRow: grid.length - GROUND_ROWS, start, hole, ...objects, wind: meta.wind || 0 };
}
